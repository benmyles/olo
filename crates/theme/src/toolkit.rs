//! The Olo look for other toolkits' programs, from the same palette.
//!
//! - **GTK 3** takes a theme by name (the GSettings key `gtk-theme`):
//!   [`GTK_THEME`] and [`GTK_THEME_DARK`], whose `gtk-3.0/gtk.css` is
//!   [`gtk3_css`]: GTK's own Adwaita with Olo's colours over it. GTK 4
//!   programs without libadwaita take the same themes' `gtk-4.0/gtk.css`
//!   ([`gtk4_theme_css`]).
//! - **GTK 4 / libadwaita** don't take themes; they take the colours in
//!   CSS variables, from a user stylesheet. [`gtk4_css`] sets them for
//!   both modes (GTK picks by the colour scheme, live).
//! - **Chrome**, left to follow the system ("GTK" in its appearance
//!   settings), takes its colours from the GTK 3 theme.

use crate::{Palette, Rgba, tint};

pub const GTK_THEME: &str = "Olo";
pub const GTK_THEME_DARK: &str = "Olo-dark";

fn hex(c: Rgba) -> String {
    if c[3] == 255 { format!("#{:02x}{:02x}{:02x}", c[0], c[1], c[2]) } else { format!("rgba({},{},{},{:.2})", c[0], c[1], c[2], c[3] as f32 / 255.0) }
}

/// The accent: what Olo marks things on with (switches, checks,
/// progress, default buttons).
fn accent(p: &Palette) -> Rgba {
    p.control_highlight
}

/// The accent as text on documents: darker in light mode, lighter in dark.
fn accent_text(p: &Palette) -> Rgba {
    match p.mode {
        crate::ThemeMode::Light => tint(p.control_highlight, 1.3),
        crate::ThemeMode::Dark => tint(p.control_highlight, 0.7),
    }
}

fn warning(p: &Palette) -> Rgba {
    match p.mode {
        crate::ThemeMode::Light => p.tab_focused_shadow,
        crate::ThemeMode::Dark => p.tab_focused_light,
    }
}

/// The sidebars of GTK's programs: a shade off the panel colour, as
/// Tracker's own lists sit on it.
fn sidebar(p: &Palette) -> Rgba {
    match p.mode {
        crate::ThemeMode::Light => tint(p.panel_background, 0.8),
        crate::ThemeMode::Dark => tint(p.panel_background, 1.15),
    }
}

/// `gtk-3.0/gtk.css` for [`GTK_THEME`] (light) or [`GTK_THEME_DARK`].
pub fn gtk3_css(p: &Palette) -> String {
    let dark = p.mode == crate::ThemeMode::Dark;
    theme_css(p, &format!("Adwaita/gtk-contained{}.css", if dark { "-dark" } else { "" }))
}

/// `gtk-4.0/gtk.css` for the same themes: what GTK 4 programs without
/// libadwaita take (libadwaita's take [`gtk4_css`]).
pub fn gtk4_theme_css(p: &Palette) -> String {
    let dark = p.mode == crate::ThemeMode::Dark;
    theme_css(p, &format!("Default/Default-{}.css", if dark { "dark" } else { "light" }))
}

/// GTK's own theme at `base` (a resource under `theme/`), in Olo's
/// colours. The selectors cover GTK 3 and GTK 4 alike.
fn theme_css(p: &Palette, base: &str) -> String {
    let dark = p.mode == crate::ThemeMode::Dark;
    let c = |c: Rgba| hex(c);
    let hover = c(if dark { tint(p.control_background, 0.85) } else { p.shine });
    let pressed = c(tint(p.control_background, crate::B_DARKEN_1_TINT));
    let border = c(p.frame_focused[if dark { 0 } else { 4 }]);
    format!(
        "/* Olo{mode}: generated by app_server from Olo's palette. */
@import url(\"resource:///org/gtk/libgtk/theme/{base}\");

@define-color theme_bg_color {panel};
@define-color theme_fg_color {panel_text};
@define-color theme_base_color {doc};
@define-color theme_text_color {doc_text};
@define-color theme_selected_bg_color {accent};
@define-color theme_selected_fg_color #ffffff;
@define-color theme_unfocused_bg_color {panel};
@define-color theme_unfocused_fg_color {panel_text};
@define-color theme_unfocused_base_color {doc};
@define-color theme_unfocused_text_color {doc_text};
@define-color theme_unfocused_selected_bg_color {list_sel};
@define-color theme_unfocused_selected_fg_color {list_sel_text};
@define-color borders {border};
@define-color unfocused_borders {border};
@define-color warning_color {warning};
@define-color error_color {failure};
@define-color success_color {success};

window.background, .background, dialog, messagedialog, notebook > header, actionbar, statusbar,
headerbar, .titlebar:not(headerbar), headerbar:backdrop, .titlebar:backdrop {{
  background-color: {panel}; background-image: none; color: {panel_text};
}}
headerbar, .titlebar:not(headerbar) {{ border-color: {border}; box-shadow: inset 0 1px {shine}; }}
.view, iconview, textview text, treeview.view, list, placessidebar, .sidebar {{
  background-color: {doc}; color: {doc_text};
}}
placessidebar, .sidebar, stacksidebar list {{ background-color: {sidebar}; }}
.view:selected, .view text:selected, treeview.view:selected, iconview:selected, row:selected,
flowboxchild:selected, label:selected, selection, *:selected {{
  background-color: {list_sel}; color: {list_sel_text};
}}
.view:selected:focus, treeview.view:selected:focus, row:selected:focus {{ background-color: {accent}; color: #ffffff; }}
button:not(.flat):not(.titlebutton):not(.sidebar-button) {{
  background-color: {control}; background-image: none; color: {control_text};
  border-color: {control_border}; box-shadow: inset 0 1px {shine}; text-shadow: none; -gtk-icon-shadow: none;
}}
button:not(.flat):not(.titlebutton):hover {{ background-color: {hover}; background-image: none; }}
button:not(.flat):not(.titlebutton):active, button:not(.flat):not(.titlebutton):checked {{
  background-color: {pressed}; background-image: none; box-shadow: none;
}}
windowcontrols > button:not(:hover):not(:active) {{ background-color: transparent; border-color: transparent; box-shadow: none; }}
button.suggested-action {{ background-color: {accent}; color: #ffffff; border-color: {control_border}; }}
button.destructive-action {{ background-color: {failure}; color: #ffffff; border-color: {control_border}; }}
entry, spinbutton:not(.vertical) {{
  background-color: {doc}; background-image: none; color: {doc_text};
  border-color: {control_border}; border-radius: 0; box-shadow: none;
}}
entry:focus, spinbutton:focus-within {{ border-color: {focus}; box-shadow: inset 0 0 0 1px {focus}; }}
menubar, menu, .menu, .context-menu, popover.background, popover.menu, popover > contents, popover > arrow {{
  background-color: {menu}; color: {menu_text};
}}
menu menuitem:hover, .menu menuitem:hover, menubar > menuitem:hover, popover modelbutton:hover {{
  background-color: {menu_sel}; color: {menu_sel_text};
}}
tooltip, tooltip.background {{ background-color: {tooltip}; color: {tooltip_text}; border-radius: 0; border: 1px solid {control_border}; }}
tooltip * {{ color: {tooltip_text}; }}
progressbar progress, levelbar block.filled {{ background-color: {status}; background-image: none; border-color: {control_border}; }}
switch:checked, check:checked, radio:checked, scale highlight {{
  background-color: {accent}; background-image: none; border-color: {control_border}; color: #ffffff;
}}
*:link, link, button.link {{ color: {link}; }}
",
        mode = if dark { " (dark)" } else { "" },
        panel = c(p.panel_background),
        panel_text = c(p.panel_text),
        doc = c(p.document_background),
        doc_text = c(p.document_text),
        accent = c(accent(p)),
        list_sel = c(p.list_selected_background),
        list_sel_text = c(p.list_selected_item_text),
        warning = c(warning(p)),
        failure = c(p.failure),
        success = c(p.success),
        shine = c(if dark { p.frame_focused[1] } else { p.shine }),
        sidebar = c(sidebar(p)),
        control = c(p.control_background),
        control_text = c(p.control_text),
        control_border = c(p.control_border),
        focus = c(p.keyboard_navigation),
        menu = c(p.menu_background),
        menu_text = c(p.menu_item_text),
        menu_sel = c(p.menu_selected_background),
        menu_sel_text = c(p.menu_selected_item_text),
        tooltip = c(p.tooltip_background),
        tooltip_text = c(p.tooltip_text),
        status = c(p.status_bar),
        link = c(accent_text(p)),
    )
}

/// libadwaita's colour variables for one mode.
fn adwaita_vars(p: &Palette) -> String {
    let border = match p.mode {
        crate::ThemeMode::Light => p.frame_focused[4],
        crate::ThemeMode::Dark => p.frame_focused[0],
    };
    let vars = [
        ("window-bg-color", p.panel_background),
        ("window-fg-color", p.panel_text),
        ("view-bg-color", p.document_background),
        ("view-fg-color", p.document_text),
        ("headerbar-bg-color", p.panel_background),
        ("headerbar-fg-color", p.panel_text),
        ("headerbar-backdrop-color", p.panel_background),
        ("headerbar-border-color", border),
        ("sidebar-bg-color", sidebar(p)),
        ("sidebar-fg-color", p.panel_text),
        ("sidebar-backdrop-color", sidebar(p)),
        ("sidebar-border-color", border),
        ("secondary-sidebar-bg-color", p.panel_background),
        ("secondary-sidebar-fg-color", p.panel_text),
        ("secondary-sidebar-backdrop-color", p.panel_background),
        ("secondary-sidebar-border-color", border),
        ("card-bg-color", p.control_background),
        ("card-fg-color", p.control_text),
        ("thumbnail-bg-color", p.control_background),
        ("thumbnail-fg-color", p.control_text),
        ("dialog-bg-color", p.panel_background),
        ("dialog-fg-color", p.panel_text),
        ("popover-bg-color", p.menu_background),
        ("popover-fg-color", p.menu_item_text),
        ("overview-bg-color", p.panel_background),
        ("overview-fg-color", p.panel_text),
        ("accent-bg-color", accent(p)),
        ("accent-fg-color", [255, 255, 255, 255]),
        ("accent-color", accent_text(p)),
        ("destructive-bg-color", p.failure),
        ("destructive-fg-color", [255, 255, 255, 255]),
        ("destructive-color", p.failure),
        ("success-bg-color", p.success),
        ("success-fg-color", [255, 255, 255, 255]),
        ("success-color", p.success),
        ("warning-bg-color", warning(p)),
        ("warning-fg-color", [0, 0, 0, 255]),
        ("warning-color", warning(p)),
        ("error-bg-color", p.failure),
        ("error-fg-color", [255, 255, 255, 255]),
        ("error-color", p.failure),
    ];
    vars.iter().map(|(k, v)| format!("    --{k}: {};\n", hex(*v))).collect()
}

/// The user stylesheet for GTK 4 and libadwaita programs: both modes,
/// chosen by the colour scheme.
pub fn gtk4_css(light: &Palette, dark: &Palette) -> String {
    format!(
        "/* Olo: generated by app_server from Olo's palette. */
@media (prefers-color-scheme: light) {{
  :root {{
{}  }}
}}
@media (prefers-color-scheme: dark) {{
  :root {{
{}  }}
}}
tooltip, tooltip.background {{ border-radius: 0; }}
",
        adwaita_vars(light),
        adwaita_vars(dark),
    )
}

/// The `index.theme` that names a GTK theme.
pub fn gtk_index(name: &str) -> String {
    format!("[Desktop Entry]\nType=X-GNOME-Metatheme\nName={name}\nComment=Olo's colours for GTK programs\nEncoding=UTF-8\n\n[X-GNOME-Metatheme]\nGtkTheme={name}\n")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn stylesheets_have_the_palette() {
        let (l, d) = (Palette::light(), Palette::dark());
        let g4 = gtk4_css(&l, &d);
        assert!(g4.contains("--window-bg-color: #d8d8d8;") && g4.contains("--window-bg-color: #2b2b2b;"));
        assert_eq!(g4.matches('{').count(), g4.matches('}').count());
        let g3 = gtk3_css(&d);
        assert!(g3.contains("gtk-contained-dark.css") && g3.contains("@define-color theme_bg_color #2b2b2b;"));
        assert_eq!(g3.matches('{').count(), g3.matches('}').count());
        assert!(!gtk3_css(&l).contains("-dark.css"));
        assert!(gtk4_theme_css(&d).contains("theme/Default/Default-dark.css"));
    }
}
