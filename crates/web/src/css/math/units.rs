use super::*;
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u8)]
pub enum RelativeUnit {
    Percentage,
    Em,
    Ex,
    Cap,
    Ch,
    Ic,
    Lh,
    Rem,
    Rex,
    Rcap,
    Rch,
    Ric,
    Rlh,
    Vw,
    Vh,
    Vi,
    Vb,
    Vmin,
    Vmax,
    Svw,
    Svh,
    Svi,
    Svb,
    Svmin,
    Svmax,
    Lvw,
    Lvh,
    Lvi,
    Lvb,
    Lvmin,
    Lvmax,
    Dvw,
    Dvh,
    Dvi,
    Dvb,
    Dvmin,
    Dvmax,
    Cqw,
    Cqh,
    Cqi,
    Cqb,
    Cqmin,
    Cqmax,
}
pub(super) enum Unit {
    Absolute(Dimension, f64),
    Relative(RelativeUnit),
}
pub(super) fn unit(name: &str) -> Option<Unit> {
    if name.len() > 8 || !name.is_ascii() {
        return None;
    }
    let mut buffer = [0u8; 8];
    for (target, source) in buffer.iter_mut().zip(name.bytes()) {
        *target = source.to_ascii_lowercase();
    }
    let name = std::str::from_utf8(&buffer[..name.len()]).ok()?;
    use Dimension::*;
    use RelativeUnit::*;
    Some(match name {
        "px" => Unit::Absolute(Length, 1.),
        "in" => Unit::Absolute(Length, 96.),
        "cm" => Unit::Absolute(Length, 96. / 2.54),
        "mm" => Unit::Absolute(Length, 96. / 25.4),
        "q" => Unit::Absolute(Length, 96. / 101.6),
        "pt" => Unit::Absolute(Length, 96. / 72.),
        "pc" => Unit::Absolute(Length, 16.),
        "deg" => Unit::Absolute(Angle, 1.),
        "grad" => Unit::Absolute(Angle, 0.9),
        "rad" => Unit::Absolute(Angle, 180. / std::f64::consts::PI),
        "turn" => Unit::Absolute(Angle, 360.),
        "s" => Unit::Absolute(Time, 1.),
        "ms" => Unit::Absolute(Time, 0.001),
        "hz" => Unit::Absolute(Frequency, 1.),
        "khz" => Unit::Absolute(Frequency, 1000.),
        "dppx" | "x" => Unit::Absolute(Resolution, 1.),
        "dpi" => Unit::Absolute(Resolution, 1. / 96.),
        "dpcm" => Unit::Absolute(Resolution, 2.54 / 96.),
        "fr" => Unit::Absolute(Flex, 1.),
        "em" => Unit::Relative(Em),
        "ex" => Unit::Relative(Ex),
        "cap" => Unit::Relative(Cap),
        "ch" => Unit::Relative(Ch),
        "ic" => Unit::Relative(Ic),
        "lh" => Unit::Relative(Lh),
        "rem" => Unit::Relative(Rem),
        "rex" => Unit::Relative(Rex),
        "rcap" => Unit::Relative(Rcap),
        "rch" => Unit::Relative(Rch),
        "ric" => Unit::Relative(Ric),
        "rlh" => Unit::Relative(Rlh),
        "vw" => Unit::Relative(Vw),
        "vh" => Unit::Relative(Vh),
        "vi" => Unit::Relative(Vi),
        "vb" => Unit::Relative(Vb),
        "vmin" => Unit::Relative(Vmin),
        "vmax" => Unit::Relative(Vmax),
        "svw" => Unit::Relative(Svw),
        "svh" => Unit::Relative(Svh),
        "svi" => Unit::Relative(Svi),
        "svb" => Unit::Relative(Svb),
        "svmin" => Unit::Relative(Svmin),
        "svmax" => Unit::Relative(Svmax),
        "lvw" => Unit::Relative(Lvw),
        "lvh" => Unit::Relative(Lvh),
        "lvi" => Unit::Relative(Lvi),
        "lvb" => Unit::Relative(Lvb),
        "lvmin" => Unit::Relative(Lvmin),
        "lvmax" => Unit::Relative(Lvmax),
        "dvw" => Unit::Relative(Dvw),
        "dvh" => Unit::Relative(Dvh),
        "dvi" => Unit::Relative(Dvi),
        "dvb" => Unit::Relative(Dvb),
        "dvmin" => Unit::Relative(Dvmin),
        "dvmax" => Unit::Relative(Dvmax),
        "cqw" => Unit::Relative(Cqw),
        "cqh" => Unit::Relative(Cqh),
        "cqi" => Unit::Relative(Cqi),
        "cqb" => Unit::Relative(Cqb),
        "cqmin" => Unit::Relative(Cqmin),
        "cqmax" => Unit::Relative(Cqmax),
        _ => return None,
    })
}
