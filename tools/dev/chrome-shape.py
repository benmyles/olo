#!/usr/bin/python3
"""chrome-shape.py SHAPE.json > crates/js/src/chrome-shape.js

What Chrome's global object and its main prototypes are, for Olo to present
as the Chrome it renders like (crates/js/src/chrome.js): from SHAPE.json,
the result of evaluating tools/dev/chrome-shape.js in Chrome on a plain
page of a secure origin (http://localhost/ will do), e.g. over its remote
debugging protocol. Run it again for each new Chrome Olo follows.

Each entry is [name, kind]: 'C:Parent:length' an interface, 'F:length' a
function, 'O:Tag' an object, 'V:value' a value, 'a' an accessor; and the
interfaces a page can construct (CHROME_CONSTRUCTIBLE). Evaluating it
constructs each interface once, so use a scratch profile."""
import json, sys

shape = json.load(open(sys.argv[1]))
# What isn't Chrome's own: Olo's launcher's, and the page's.
SKIP = {'__oloPasskeys', 'cdc_adoQpoasnfa76pfcZLmcfl_Array'}

def entries(items):
    out = []
    for e in items:
        name = e[0]
        if name in SKIP:
            continue
        if e[1] == 'a':
            out.append([name, 'a'])
        elif e[1] == 'd':
            out.append([name, e[-1]])
    return out

window = entries(shape['window'])
protos = {k: entries(v) for k, v in shape['protos'].items() if k in ('Navigator', 'Document', 'HTMLDocument', 'Node', 'EventTarget', 'Element', 'HTMLElement', 'SVGElement', 'CharacterData', 'Text', 'DocumentType', 'DocumentFragment', 'Screen')}
print('// Generated by tools/dev/chrome-shape.py from Chrome %s on Linux: its global' % shape.get('version', '157.0.8103.38'))
print("// object's own properties in order, and its main prototypes' (see")
print('// chrome.js). Regenerate it for each new Chrome Olo follows.')
print('const CHROME_WINDOW = ' + json.dumps(window, separators=(',', ':')) + ';')
print('const CHROME_PROTOS = ' + json.dumps(protos, separators=(',', ':')) + ';')
print('const CHROME_CONSTRUCTIBLE = new Set(' + json.dumps([n for n in shape.get('constructible', []) if n not in SKIP], separators=(',', ':')) + ');')
