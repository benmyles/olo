#!/usr/bin/python3
"""Regenerate our table from WHATWG's named-character-reference data.

Development tool only; the engine never downloads executable or generated
source at build/run time. Updating the pin is a separately reviewed change.
"""
import hashlib
import json
from pathlib import Path
import urllib.request

URL = "https://html.spec.whatwg.org/entities.json"
SHA256 = "d741d877ac77c4194c4ad526b5b4a19aef8dfe411ab840a466891cdbb9f362e6"
ROOT = Path(__file__).resolve().parents[2]


def rust_string(value):
    return '"' + ''.join(
        '\\u{' + format(ord(c), 'x') + '}' if not (32 <= ord(c) < 127)
        else '\\' + c if c in ('"', '\\') else c for c in value
    ) + '"'


def main():
    data = urllib.request.urlopen(URL, timeout=30).read()
    assert hashlib.sha256(data).hexdigest() == SHA256, "WHATWG data changed; review and update the pin"
    entities = json.loads(data)
    lines = [
        "// Generated by tools/browser/update-entities.py from WHATWG entities.json.",
        "// SHA-256: " + SHA256,
        "// https://html.spec.whatwg.org/entities.json (2026-11-04).",
        "// Data: WHATWG HTML, CC BY 4.0; see NOTICE.md. Do not edit.",
        "#[rustfmt::skip]",
        "pub(super) static ENTITIES: &[(&str, &str)] = &[",
    ]
    for key, value in sorted(entities.items()):
        lines.append(f"    ({rust_string(key[1:])}, {rust_string(value['characters'])}),")
    lines.append("];\n")
    (ROOT / "crates/web/src/html/entities.rs").write_text('\n'.join(lines))
    print(f"Generated {len(entities)} named references")


if __name__ == '__main__':
    main()
